const languageButtons = document.querySelectorAll("[data-lang-option]");
const supportedLanguages = new Set(Object.keys(translations));
const storageKey = "poligram-language";
const browserLanguage = navigator.language.slice(0, 2).toLowerCase();

let currentLanguage = supportedLanguages.has(browserLanguage) ? browserLanguage : "ru";

try {
    const savedLanguage = localStorage.getItem(storageKey);
    if (supportedLanguages.has(savedLanguage)) {
        currentLanguage = savedLanguage;
    }
} catch {
    // Local storage can be blocked in some browsers or private contexts.
}

const resolveTranslation = (language, key) => {
    const source = translations[language] ?? translations.ru;
    return key.split(".").reduce((value, part) => value?.[part], source);
};

const applyLanguage = (language) => {
    const dictionary = translations[language] ?? translations.ru;

    currentLanguage = language;
    document.documentElement.lang = language;
    document.title = dictionary.pageTitle;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.dataset.i18n;
        const value = resolveTranslation(language, key);
        const attrs = (element.dataset.i18nAttr ?? "").split(",").map((item) => item.trim()).filter(Boolean);

        if (attrs.length > 0) {
            attrs.forEach((attr) => {
                element.setAttribute(attr, value);
            });
            return;
        }

        element.textContent = value;
    });

    languageButtons.forEach((button) => {
        const isActive = button.dataset.langOption === language;
        button.setAttribute("aria-pressed", String(isActive));
        button.classList.toggle("is-active", isActive);
    });

    try {
        localStorage.setItem(storageKey, language);
    } catch {
        // Ignore storage failures and continue with the selected language.
    }

    document.dispatchEvent(new CustomEvent("poligram:language-change", { detail: { language } }));
};

languageButtons.forEach((button) => {
    button.addEventListener("click", () => {
        const nextLanguage = button.dataset.langOption;

        if (!supportedLanguages.has(nextLanguage)) {
            return;
        }

        applyLanguage(nextLanguage);
    });
});

window.PoligramI18n = {
    getCurrentLanguage: () => currentLanguage,
    setLanguage: applyLanguage,
    t: resolveTranslation
};

applyLanguage(currentLanguage);
